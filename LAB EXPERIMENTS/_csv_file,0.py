import pandas as pd
import csv

# Step 1: Create a CSV training dataset
filename = "training_data.csv"

training_data = [
    ["Sky", "Temperature", "Humidity", "Wind",
     "Water", "Forecast", "EnjoySport"],

    ["Sunny", "Warm", "Normal", "Strong",
     "Warm", "Same", "Yes"],

    ["Sunny", "Warm", "High", "Strong",
     "Warm", "Same", "Yes"],

    ["Rainy", "Cold", "High", "Strong",
     "Warm", "Change", "No"],

    ["Sunny", "Warm", "High", "Strong",
     "Cool", "Change", "Yes"]
]

with open(filename, "w", newline="") as file:
    writer = csv.writer(file)
    writer.writerows(training_data)

print("CSV file created successfully!\n")

# Step 2: Read CSV file
data = pd.read_csv(filename)

print("Training Dataset:")
print(data)

# Step 3: Separate attributes and target
X = data.iloc[:, :-1].values
Y = data.iloc[:, -1].values

n = len(X[0])

# Step 4: Initialize S and G
S = ['0'] * n
G = [['?' for _ in range(n)]]

# Step 5: Candidate-Elimination Algorithm
for i, example in enumerate(X):

    if Y[i] == 'Yes':

        # Update Specific boundary
        for j in range(n):

            if S[j] == '0':
                S[j] = example[j]

            elif S[j] != example[j]:
                S[j] = '?'

        # Remove inconsistent hypotheses from G
        G = [
            g for g in G
            if all(g[j] == '?' or g[j] == example[j]
                   for j in range(n))
        ]

    elif Y[i] == 'No':

        new_G = []

        # Specialize General boundary
        for g in G:

            for j in range(n):

                if g[j] == '?' and S[j] != '?' and S[j] != '0':

                    if S[j] != example[j]:

                        h = g.copy()
                        h[j] = S[j]

                        # Check previous positive examples
                        valid = True

                        for k in range(i):

                            if Y[k] == 'Yes':

                                if not all(
                                    h[m] == '?' or h[m] == X[k][m]
                                    for m in range(n)
                                ):
                                    valid = False
                                    break

                        if valid:
                            new_G.append(h)

        G = new_G

    # Remove duplicate hypotheses
    G = [list(x) for x in set(tuple(h) for h in G)]

    print("\nAfter Example", i + 1)
    print("Specific Boundary S:", S)
    print("General Boundary G:", G)

# Step 6: Display final results
print("\n================================")
print("FINAL RESULTS")
print("================================")

print("\nSpecific Boundary (S):")
print(S)

print("\nGeneral Boundary (G):")

for h in G:
    print(h)

print("\nCandidate-Elimination completed successfully!")