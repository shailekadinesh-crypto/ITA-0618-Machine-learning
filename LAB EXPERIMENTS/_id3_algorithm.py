import pandas as pd
import math
from collections import Counter
from pprint import pprint

# Step 1: Create dataset
data = {
    'Outlook': ['Sunny', 'Sunny', 'Overcast', 'Rain',
                'Rain', 'Rain', 'Overcast', 'Sunny',
                'Sunny', 'Rain', 'Sunny', 'Overcast',
                'Overcast', 'Rain'],

    'Temperature': ['Hot', 'Hot', 'Hot', 'Mild',
                    'Cool', 'Cool', 'Cool', 'Mild',
                    'Cool', 'Mild', 'Mild', 'Mild',
                    'Hot', 'Mild'],

    'Humidity': ['High', 'High', 'High', 'High',
                 'Normal', 'Normal', 'Normal', 'High',
                 'Normal', 'Normal', 'Normal', 'High',
                 'Normal', 'High'],

    'Wind': ['Weak', 'Strong', 'Weak', 'Weak',
             'Weak', 'Strong', 'Strong', 'Weak',
             'Weak', 'Weak', 'Strong', 'Strong',
             'Weak', 'Strong'],

    'PlayTennis': ['No', 'No', 'Yes', 'Yes',
                   'Yes', 'No', 'Yes', 'No',
                   'Yes', 'Yes', 'Yes', 'Yes',
                   'Yes', 'No']
}

df = pd.DataFrame(data)

print("Training Dataset:")
print(df)

# Step 2: Calculate Entropy
def entropy(target):
    counts = Counter(target)
    total = len(target)

    result = 0

    for count in counts.values():
        p = count / total
        result -= p * math.log2(p)

    return result

# Step 3: Calculate Information Gain
def information_gain(dataset, attribute, target):
    total_entropy = entropy(dataset[target])
    total = len(dataset)

    weighted_entropy = 0

    for value in dataset[attribute].unique():
        subset = dataset[dataset[attribute] == value]

        weighted_entropy += (
            len(subset) / total
        ) * entropy(subset[target])

    return total_entropy - weighted_entropy

# Step 4: Build ID3 Decision Tree
def id3(dataset, attributes, target):

    # If all examples belong to one class
    if len(dataset[target].unique()) == 1:
        return dataset[target].iloc[0]

    # If no attributes remain
    if not attributes:
        return dataset[target].mode()[0]

    # Select attribute with maximum Information Gain
    best_attribute = max(
        attributes,
        key=lambda attr: information_gain(
            dataset, attr, target
        )
    )

    tree = {best_attribute: {}}

    remaining_attributes = [
        attr for attr in attributes
        if attr != best_attribute
    ]

    # Create branches
    for value in dataset[best_attribute].unique():

        subset = dataset[
            dataset[best_attribute] == value
        ]

        tree[best_attribute][value] = id3(
            subset,
            remaining_attributes,
            target
        )

    return tree

# Step 5: Build the decision tree
attributes = list(df.columns[:-1])

decision_tree = id3(
    df,
    attributes,
    'PlayTennis'
)

print("\nDecision Tree:")
pprint(decision_tree)

# Step 6: Classify a new sample
def predict(tree, sample):

    if not isinstance(tree, dict):
        return tree

    attribute = next(iter(tree))
    value = sample.get(attribute)

    if value not in tree[attribute]:
        return "Unknown"

    return predict(tree[attribute][value], sample)

