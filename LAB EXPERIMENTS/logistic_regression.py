# Implementation of Logistic Regression Algorithm

import numpy as np
from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix
from sklearn.metrics import classification_report

# Step 1: Load Iris dataset
iris = load_iris()

X = iris.data
Y = iris.target

# Step 2: Split dataset into training and testing data
X_train, X_test, Y_train, Y_test = train_test_split(
    X, Y, test_size=0.2, random_state=42
)

# Step 3: Create Logistic Regression model
model = LogisticRegression(max_iter=200)

# Step 4: Train the model
model.fit(X_train, Y_train)

# Step 5: Predict test data
Y_pred = model.predict(X_test)

# Step 6: Display actual and predicted values
print("Logistic Regression Algorithm")
print("-----------------------------")

print("\nActual Values:")
print(Y_test)

print("\nPredicted Values:")
print(Y_pred)

# Step 7: Calculate accuracy
accuracy = accuracy_score(Y_test, Y_pred)

print("\nAccuracy:", accuracy * 100, "%")

# Step 8: Display confusion matrix
print("\nConfusion Matrix:")
print(confusion_matrix(Y_test, Y_pred))

# Step 9: Display classification report
print("\nClassification Report:")
print(classification_report(
    Y_test,
    Y_pred,
    target_names=iris.target_names
))

# Step 10: Predict a new sample
new_sample = np.array([[5.1, 3.5, 1.4, 0.2]])

prediction = model.predict(new_sample)

print("\nNew Sample:", new_sample)
print("Predicted Flower:",
      iris.target_names[prediction[0]])

print("\nLogistic Regression Completed Successfully!")