import numpy as np

# Step 1: Create XOR dataset
X = np.array([
    [0, 0],
    [0, 1],
    [1, 0],
    [1, 1]
])

Y = np.array([
    [0],
    [1],
    [1],
    [0]
])

# Step 2: Initialize parameters
np.random.seed(42)

input_neurons = 2
hidden_neurons = 4
output_neurons = 1

# Initialize weights and biases
W1 = np.random.randn(input_neurons, hidden_neurons)
b1 = np.zeros((1, hidden_neurons))

W2 = np.random.randn(hidden_neurons, output_neurons)
b2 = np.zeros((1, output_neurons))

# Learning rate
learning_rate = 0.5
epochs = 10000

# Step 3: Sigmoid activation function
def sigmoid(x):
    return 1 / (1 + np.exp(-x))

# Derivative of sigmoid function
def sigmoid_derivative(x):
    return x * (1 - x)

# Step 4: Training using Backpropagation
for epoch in range(epochs):

    # Forward propagation
    hidden_input = np.dot(X, W1) + b1
    hidden_output = sigmoid(hidden_input)

    final_input = np.dot(hidden_output, W2) + b2
    predicted_output = sigmoid(final_input)

    # Calculate error
    error = Y - predicted_output

    # Backward propagation
    output_delta = error * sigmoid_derivative(
        predicted_output
    )

    hidden_error = np.dot(output_delta, W2.T)

    hidden_delta = hidden_error * sigmoid_derivative(
        hidden_output
    )

    # Update weights and biases
    W2 += learning_rate * np.dot(
        hidden_output.T, output_delta
    )

    b2 += learning_rate * np.sum(
        output_delta, axis=0, keepdims=True
    )

    W1 += learning_rate * np.dot(
        X.T, hidden_delta
    )

    b1 += learning_rate * np.sum(
        hidden_delta, axis=0, keepdims=True
    )

    # Display loss
    if (epoch + 1) % 2000 == 0:
        loss = np.mean(error ** 2)
        print("Epoch:", epoch + 1, "Loss:", loss)

# Step 5: Test the trained neural network
print("\nTesting the Neural Network:")

hidden_output = sigmoid(np.dot(X, W1) + b1)
predicted_output = sigmoid(np.dot(hidden_output, W2) + b2)

for i in range(len(X)):
    print(
        "Input:", X[i],
        "Actual:", Y[i][0],
        "Predicted:", round(predicted_output[i][0], 4),
        "Class:", int(predicted_output[i][0] >= 0.5)
    )

print("\nANN Training and Testing Completed Successfully!")