# FIND-S Algorithm Implementation

import pandas as pd

# Training dataset
data = [
    ['Sunny', 'Warm', 'Normal', 'Strong', 'Warm', 'Same', 'Yes'],
    ['Sunny', 'Warm', 'High', 'Strong', 'Warm', 'Same', 'Yes'],
    ['Rainy', 'Cold', 'High', 'Strong', 'Warm', 'Change', 'No'],
    ['Sunny', 'Warm', 'High', 'Strong', 'Cool', 'Change', 'Yes']
]

# Define column names
columns = ['Sky', 'Temperature', 'Humidity',
           'Wind', 'Water', 'Forecast', 'EnjoySport']

df = pd.DataFrame(data, columns=columns)

print("Training Dataset:")
print(df)

# Initialize hypothesis with the first positive example
hypothesis = None

# Apply FIND-S algorithm
for index, row in df.iterrows():

    if row['EnjoySport'] == 'Yes':

        example = list(row[:-1])

        if hypothesis is None:
            hypothesis = example.copy()

        else:
            for i in range(len(hypothesis)):
                if hypothesis[i] != example[i]:
                    hypothesis[i] = '?'

        print("Hypothesis after example", index + 1, ":", hypothesis)

# Display final hypothesis
print("\nFinal Most Specific Hypothesis:")
print(hypothesis)