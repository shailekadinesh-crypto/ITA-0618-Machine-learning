import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
from sklearn.metrics import r2_score

# Sample dataset
X = np.array([1, 2, 3, 4, 5, 6]).reshape(-1, 1)
y = np.array([2, 5, 10, 17, 26, 37])

# Linear Regression
linear_model = LinearRegression()
linear_model.fit(X, y)
y_linear = linear_model.predict(X)

# Polynomial Regression
poly = PolynomialFeatures(degree=2)
X_poly = poly.fit_transform(X)

poly_model = LinearRegression()
poly_model.fit(X_poly, y)
y_poly = poly_model.predict(X_poly)

# Display results
print("Linear Regression R2 Score:", r2_score(y, y_linear))
print("Polynomial Regression R2 Score:", r2_score(y, y_poly))

# Plot comparison
plt.scatter(X, y, color='blue', label='Actual Data')
plt.plot(X, y_linear, color='red', label='Linear Regression')
plt.plot(X, y_poly, color='green', label='Polynomial Regression')

plt.xlabel("X")
plt.ylabel("Y")
plt.title("Linear vs Polynomial Regression")
plt.legend()
plt.show()